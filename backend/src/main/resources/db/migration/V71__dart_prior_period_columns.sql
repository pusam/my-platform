-- 첫 DART 분기 수집(V69, 11/5 09:37) 뒤 네이버와 대조하니 80종목 중 대부분이 맞았지만 두 부류가 남았다.
--   ① 연중에 연결을 시작한 회사 — 최근 9개 보고서 안에서 연결/별도가 바뀐 곳이 78종목이다. 두 기준의 누적은 뺄 수 없어 그 분기가 비고,
--      DART 행이 있는 601종목 중 70종목이 최근 4분기를 못 채운다(한화엔진: 2025 3분기 별도 10,032억, 2025 연간 연결 13,711억).
--   ② 중단영업 재분류 — 나중 보고서의 누적이 앞 보고서보다 작아 분기 매출이 음수가 된다(9종목. 188260 2025 4분기 −49억, 그래서 합계도 틀린다).
-- 최근 4분기는 분기를 더하지 않고 최신 누적 + 직전 연간 − 전년 동기 누적으로 만들면 둘 다 풀린다 — 전년 동기 누적을 최신 보고서 자신의
-- 비교 칸에서 읽으므로 기준이 같고 재분류도 반영돼 있다(지배주주 순이익 TTM 과 같은 식). 그 비교 칸을 보존한다.
--
-- income_parsed 를 비워 분기를 채우는 종목의 보고서를 한 번 다시 받는다(약 5,000호출, 약 15분). 빈 칸을 부팅 따라잡기가 알아본다.
ALTER TABLE dart_controlling_financial
    ADD COLUMN revenue_prev DECIMAL(15,2) NULL COMMENT '전년 동기 누적 매출(억원) — 사업보고서는 전년 연간',
    ADD COLUMN operating_profit_prev DECIMAL(15,2) NULL COMMENT '전년 동기 누적 영업이익(억원)',
    ADD COLUMN total_net_income_prev DECIMAL(15,2) NULL COMMENT '전년 동기 누적 당기순이익(억원, 비지배 포함)';

UPDATE dart_controlling_financial SET income_parsed = 0;
