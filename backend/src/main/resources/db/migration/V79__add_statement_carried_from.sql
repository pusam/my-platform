-- V79: 재무제표 값을 이어 쓴 행의 '처음 받은 날' (2026-11-13)
--
-- ## 왜
--
-- 2026-11-12 08:30 회차부터 KIS 재무 호출 세 가지가 전 종목에서 실패했다(재무비율 주소는 404, 손익계산서·재무상태표는 '호출 전처리
-- 오류'. 우리 요청은 바뀌지 않았고 공식 샘플과 같다). 그날부터 일별 행 2,602개 가운데 매출·영업이익·순이익은 533개, 부채비율은 578개만
-- 남았다(전날 2,498·2,564). 수집은 '성공 2602, 실패 0'으로 끝났다.
--
-- 재무제표 값은 분기에 한 번 바뀐다 — 호출이 실패한 날의 값은 직전에 받은 값과 같다. 그래서 호출이 '실패'한 종목만(KIS 가 자료 없음·
-- 묵음이라고 답한 종목은 그대로 모른다) 직전 일별 행의 손익·재무상태표 값을 쓰고, 그 값을 KIS 에서 처음 받은 날을 이 칸에 남긴다.
-- 이어 쓴 행을 다음 날 또 이어 써도 이 날짜는 그대로다. 30일(financial.statement-carry.max-days)이 지나면 이어 쓰지 않는다.
--
-- NULL = 그날 받은 값(또는 값 없음). 관제실 '재무 입력층'이 이 칸으로 이어 쓴 종목 수와 가장 오래된 날짜를 말한다.
ALTER TABLE stock_financial_data
    ADD COLUMN statement_carried_from DATE NULL COMMENT '손익·재무상태표 값을 KIS 에서 처음 받은 날 — 이어 쓴 행만(오늘 받았으면 NULL)';
