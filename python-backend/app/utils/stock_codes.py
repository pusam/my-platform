def get_stock_name(code: str) -> str:
    """종목코드 → 이름"""
    info = STOCKS.get(code)
    return info[0] if info else code


def to_yf_ticker(code: str) -> str:
    """KRX 코드 → yfinance 티커 (005930 → 005930.KS)"""
    info = STOCKS.get(code)
    suffix = info[1] if info else "KS"
    return f"{code}.{suffix}"


def to_yf_tickers(codes: list[str]) -> list[str]:
    """복수 KRX 코드 → yfinance 티커 리스트"""
    return [to_yf_ticker(c) for c in codes]


def from_yf_ticker(yf_ticker: str) -> str:
    """yfinance 티커 → KRX 코드 (005930.KS → 005930)"""
    return yf_ticker.split(".")[0]
